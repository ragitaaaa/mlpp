#' Plot continuous spatial predictions from a fitted mlpp model
#'
#' Generates a spatial intensity or log-intensity (`link`) surface map using the
#' `spatstat` plotting engine.
#'
#' @param x An `mlpp_model` object (e.g., fitted via [fit_gbpp()]).
#' @param newdata A named list of spatial covariates (`im`, `linim`, or `linfun`)
#'   or a spatial window (`owin`) / linear network (`linnet`).
#' @param type Scale of prediction to plot: `"intensity"` (default) or `"link"`.
#' @param overlay_points Logical; if `TRUE`, overlays `pts` on the prediction map.
#'   Default is `FALSE`.
#' @param pts A point pattern (`ppp` or `lpp`) to overlay when `overlay_points = TRUE`.
#'   Default is `NULL`.
#' @param eps Spatial resolution (grid spacing or linear network sample spacing).
#'   Default is `NULL`.
#' @param dimyx Spatial grid dimensions for planar `im` predictions. Default is `NULL`.
#' @param ... Additional graphical arguments passed to `spatstat.geom::plot.im`
#'   or `spatstat.linnet::plot.linim`.
#'
#' @details
#' Evaluates predictions across planar pixel grids (`im`) or linear networks
#' (`linim`) directly on the requested scale (`"intensity"` or `"link"`) without
#' post-hoc exponentiation truncation, then renders the resulting spatial image.
#'
#' @return Invisibly returns the plotted `spatstat.geom::im` or
#'   `spatstat.linnet::linim` object.
#'
#' @references
#' Baddeley, A., Rubak, E., & Turner, R. (2015). *Spatial Point Patterns:
#' Methodology and Applications with R*. Chapman and Hall/CRC.
#'
#' Baddeley, A., Nair, G., Rakshit, S., McSwiggan, G., & Davies, T. M. (2021).
#' Analysing point patterns on networks --- A review. *Spatial Statistics*,
#' 42, 100435. \doi{10.1016/j.spasta.2020.100435}
#'
#' @seealso [fit_gbpp()], [predict.mlpp_model()], [explain_mlpp()]
#'
#' @examples
#' if (requireNamespace("spatstat.random", quietly = TRUE) &&
#'     reticulate::py_available() &&
#'     reticulate::py_module_available("xgboost")) {
#'   win <- spatstat.geom::square(1)
#'   pts <- spatstat.random::runifpoint(20, win = win)
#'   cov_x <- spatstat.geom::as.im(function(x, y) x, W = win)
#'   dat <- prepare_mlpp(pts, covariates = list(x = cov_x), nd = 16L)
#'   fit <- fit_gbpp(dat, engine = "xgboost", objective = "poisson", n_trees = 10L)
#'   pred_im <- plot(fit, newdata = list(x = cov_x), dimyx = c(16, 16))
#' }
#' @export
plot.mlpp_model <- function(
  x,
  newdata,
  type = c("intensity", "link"),
  overlay_points = FALSE,
  pts = NULL,
  eps = NULL,
  dimyx = NULL,
  ...
) {
  type <- match.arg(type)

  if (missing(newdata)) {
    stop("`newdata` must be supplied to generate a continuous spatial plot.", call. = FALSE)
  }

  is_network <- inherits(newdata, "linnet") ||
    (is.list(newdata) && length(newdata) > 0 &&
      all(vapply(newdata, inherits, logical(1), what = c("linim", "linfun"))))

  spatial_obj <- if (is_network) {
    .pred_linim(x, newdata = newdata, eps = eps, scale = type)
  } else {
    .pred_im(x, newdata = newdata, eps = eps, dimyx = dimyx, scale = type)
  }

  graphics::plot(spatial_obj, ...)

  if (overlay_points) {
    if (is.null(pts)) {
      warning("`pts` must be provided to overlay points.", call. = FALSE)
    } else {
      graphics::plot(pts, add = TRUE, col = "black", pch = 16, cex = 0.5)
    }
  }

  invisible(spatial_obj)
}

#' Plot Stochastic Thinning Cross-Validation Folds
#'
#' Visualizes the independent stochastic thinning folds generated by [cv_mlpp()].
#' Displays the spatial domain alongside the retained test events for each fold.
#'
#' @param x An object of class `mlpp_cv`.
#' @param separate Logical. If `TRUE` (default), plots each fold in a separate
#'   panel. If `FALSE`, plots all folds in a single panel with different colors.
#' @param ... Additional arguments passed to `plot()`.
#'
#' @details
#' Extracts event locations (`y == 1`) from each held-out thinning fold in
#' `x$folds` and supports both planar (`owin`) and linear-network (`linnet`)
#' fold domains (falling back to event coordinate bounds when `window` is
#' `NULL`). When `separate = TRUE`, arranges `V` panels in a balanced grid via
#' `graphics::par(mfrow = ...)`, restoring the caller's graphical parameters via
#' `on.exit()`. When `separate = FALSE`, overlays all folds on a single spatial
#' domain with distinct colors and a legend.
#'
#' @return Invisibly returns the original object `x`.
#'
#' @references
#' Cronie, O., Moradi, M., & Biscio, C. A. N. (2024). A cross-validation-based
#' statistical theory for point processes. *Biometrika*, 111(2), 625--641.
#' \doi{10.1093/biomet/asad041}
#'
#' @seealso [cv_mlpp()], [print.mlpp_cv()]
#'
#' @examples
#' win <- spatstat.geom::square(1)
#' f1 <- list(
#'   y = c(1, 1, 0),
#'   locations = data.frame(x = c(0.2, 0.7, 0.5), y = c(0.3, 0.8, 0.5)),
#'   window = win
#' )
#' f2 <- list(
#'   y = c(1, 0),
#'   locations = data.frame(x = c(0.4, 0.5), y = c(0.6, 0.5)),
#'   window = win
#' )
#' cv_demo <- structure(
#'   list(
#'     metrics = list(
#'       loglik_mean = -1.2, loglik_sd = 0.1,
#'       deviance_mean = 2.4, deviance_sd = 0.2
#'     ),
#'     folds = list(f1, f2),
#'     type = "planar"
#'   ),
#'   class = "mlpp_cv"
#' )
#' plot(cv_demo, separate = FALSE)
#' @export
plot.mlpp_cv <- function(x, separate = TRUE, ...) {
  if (!inherits(x, "mlpp_cv")) {
    stop("`x` must be an `mlpp_cv` object.", call. = FALSE)
  }

  folds <- length(x$folds)

  extract_event_coords <- function(locs_obj, idx) {
    if (inherits(locs_obj, c("ppp", "lpp"))) {
      as.data.frame(spatstat.geom::coords(locs_obj))[idx, , drop = FALSE]
    } else {
      as.data.frame(locs_obj)[idx, , drop = FALSE]
    }
  }

  if (separate) {
    nr <- floor(sqrt(folds))
    nc <- ceiling(folds / nr)

    old_par <- graphics::par(mfrow = c(nr, nc), mar = c(1, 1, 3, 1))
    on.exit(graphics::par(old_par))
    for (k in seq_len(folds)) {
      f <- x$folds[[k]]
      idx_events <- f$y == 1
      locs <- extract_event_coords(f$locations, idx_events)

      if (!is.null(f$window)) {
        graphics::plot(
          f$window,
          main = paste("Fold", k, "\nEvents:", sum(idx_events)),
          ...
        )
      } else {
        graphics::plot(
          locs$x, locs$y,
          main = paste("Fold", k, "\nEvents:", sum(idx_events)),
          type = "n", xlab = "", ylab = "", axes = FALSE, ...
        )
      }

      graphics::points(locs$x, locs$y, pch = 20, col = "black", cex = 0.6)
    }
  } else {
    f1 <- x$folds[[1]]
    if (!is.null(f1$window)) {
      graphics::plot(f1$window, main = "Stochastic Thinning Folds", ...)
    } else {
      all_coords <- do.call(
        rbind,
        lapply(x$folds, function(f) extract_event_coords(f$locations, f$y == 1))
      )
      graphics::plot(
        all_coords$x, all_coords$y,
        main = "Stochastic Thinning Folds",
        type = "n", xlab = "", ylab = "", axes = FALSE, ...
      )
    }

    cols <- grDevices::rainbow(folds)
    for (k in seq_len(folds)) {
      f <- x$folds[[k]]
      idx_events <- f$y == 1
      locs <- extract_event_coords(f$locations, idx_events)
      graphics::points(locs$x, locs$y, pch = 20, col = cols[k], cex = 0.6)
    }
    graphics::legend(
      "topright",
      legend = paste("Fold", seq_len(folds)),
      col = cols, pch = 20, bty = "n"
    )
  }

  invisible(x)
}

#' Print Stochastic Thinning Cross-Validation Summary
#'
#' Displays the number of folds together with mean +/- standard deviation of
#' held-out Poisson deviance and Poisson log-likelihood across folds.
#'
#' @param x An object of class `mlpp_cv`.
#' @param ... Additional arguments (currently unused).
#'
#' @details
#' Summarizes `x$metrics$deviance_mean`, `x$metrics$deviance_sd`,
#' `x$metrics$loglik_mean`, and `x$metrics$loglik_sd` produced by [cv_mlpp()].
#'
#' @return Invisibly returns `x`.
#'
#' @seealso [cv_mlpp()], [plot.mlpp_cv()]
#'
#' @examples
#' cv_demo <- structure(
#'   list(
#'     metrics = list(
#'       loglik_mean = -1.2, loglik_sd = 0.1,
#'       deviance_mean = 2.4, deviance_sd = 0.2
#'     ),
#'     folds = list(list(fold = 1L), list(fold = 2L)),
#'     type = "planar"
#'   ),
#'   class = "mlpp_cv"
#' )
#' print(cv_demo)
#' @keywords internal
#' @export
print.mlpp_cv <- function(x, ...) {
  cat("Stochastic Thinning Cross-Validation Results\n")
  cat("--------------------------------------------\n")
  cat("Number of folds :", length(x$folds), "\n")
  cat(
    "Deviance        :",
    sprintf("%.4f +/- %.4f\n", x$metrics$deviance_mean, x$metrics$deviance_sd)
  )
  cat(
    "Log-likelihood  :",
    sprintf("%.4f +/- %.4f\n", x$metrics$loglik_mean, x$metrics$loglik_sd)
  )
  invisible(x)
}
